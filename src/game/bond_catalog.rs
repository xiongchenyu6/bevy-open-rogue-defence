#[derive(Debug, Clone, Copy)]
pub struct BondCardDef {
    pub id: &'static str,
    pub name: &'static str,
    pub name_en: &'static str,
    pub family: BondId,
    pub rarity: Rarity,
    pub icon: &'static str,
    pub description: &'static str,
    pub description_en: &'static str,
    pub effects: &'static [BondEffect],
}
#[derive(Debug, Clone, Copy)]
pub struct BondBonus {
    pub required: u8,
    pub effects: &'static [BondEffect],
    pub description: &'static str,
    pub description_en: &'static str,
}
#[derive(Debug, Clone, Copy)]
pub struct BondFamilyDef {
    pub id: &'static str,
    pub name: &'static str,
    pub name_en: &'static str,
    pub icon: &'static str,
    pub members: &'static [BondCardId],
    pub prerequisite: Option<BondId>,
    pub bonuses: &'static [BondBonus],
    pub favored_tags: &'static [Tag],
}

